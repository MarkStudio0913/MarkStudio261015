  let lang = 'zh-CN';

  function setLangCore(l) {
    if (!DICT[l]) l = 'zh-CN';
    lang = l;
  }

  function t(key, params) {
    let s = (DICT[lang] && DICT[lang][key]) || (DICT['zh-CN'] && DICT['zh-CN'][key]) || key;
    if (params) for (const k in params) s = s.split('{' + k + '}').join(String(params[k]));
    return s;
  }

  function curLang() { return lang; }

  function applyDom() {
    document.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-ph]').forEach((n) => { n.setAttribute('placeholder', t(n.getAttribute('data-i18n-ph'))); });
    document.querySelectorAll('[data-i18n-tip]').forEach((n) => { n.setAttribute('title', t(n.getAttribute('data-i18n-tip'))); });
    document.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.getAttribute('data-i18n-html')); });
  }

  function setLang(l) {
    setLangCore(l);
    try { document.documentElement.lang = curLang(); } catch (e) { }
    try { applyDom(); } catch (e) { }
    try { document.dispatchEvent(new CustomEvent('i18n-changed', { detail: { lang: curLang() } })); } catch (e) { }
  }

  if (typeof window !== 'undefined') {
    window.t = t;
    window.setLang = setLang;
    window.i18nLang = curLang;
    window.i18nApplyDom = applyDom;
  }

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = { t, setLang, setLangCore, curLang, applyDom, DICT };
  }
